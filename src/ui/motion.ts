export function motionDuration(reducedMotion: boolean, duration: number): number {
  return reducedMotion ? 0 : duration;
}

export function staggerDelay(index: number, step: number, maxIndex: number): number {
  return Math.min(Math.max(index, 0), maxIndex) * step;
}
